pub(in crate::runtime::strings) fn remove_diacritics_value(value: &str) -> String {
    let mut output = String::new();
    for ch in value.chars() {
        output.push_str(&strip_diacritic_char(ch));
    }
    output
}

fn strip_diacritic_char(ch: char) -> String {
    match ch {
        'À' | 'Á' | 'Â' | 'Ã' | 'Ä' | 'Å' | 'Ā' | 'Ă' | 'Ą' | 'Ǎ' | 'Ȁ' | 'Ȃ' => {
            "A".into()
        }
        'à' | 'á' | 'â' | 'ã' | 'ä' | 'å' | 'ā' | 'ă' | 'ą' | 'ǎ' | 'ȁ' | 'ȃ' => {
            "a".into()
        }
        'Ç' | 'Ć' | 'Ĉ' | 'Ċ' | 'Č' => "C".into(),
        'ç' | 'ć' | 'ĉ' | 'ċ' | 'č' => "c".into(),
        'Ð' | 'Ď' | 'Đ' => "D".into(),
        'ð' | 'ď' | 'đ' => "d".into(),
        'È' | 'É' | 'Ê' | 'Ë' | 'Ē' | 'Ĕ' | 'Ė' | 'Ę' | 'Ě' | 'Ȅ' | 'Ȇ' => "E".into(),
        'è' | 'é' | 'ê' | 'ë' | 'ē' | 'ĕ' | 'ė' | 'ę' | 'ě' | 'ȅ' | 'ȇ' => "e".into(),
        'Ĝ' | 'Ğ' | 'Ġ' | 'Ģ' => "G".into(),
        'ĝ' | 'ğ' | 'ġ' | 'ģ' => "g".into(),
        'Ĥ' | 'Ħ' => "H".into(),
        'ĥ' | 'ħ' => "h".into(),
        'Ì' | 'Í' | 'Î' | 'Ï' | 'Ĩ' | 'Ī' | 'Ĭ' | 'Į' | 'İ' | 'Ǐ' | 'Ȉ' | 'Ȋ' => {
            "I".into()
        }
        'ì' | 'í' | 'î' | 'ï' | 'ĩ' | 'ī' | 'ĭ' | 'į' | 'ı' | 'ǐ' | 'ȉ' | 'ȋ' => {
            "i".into()
        }
        'Ĵ' => "J".into(),
        'ĵ' => "j".into(),
        'Ķ' => "K".into(),
        'ķ' => "k".into(),
        'Ĺ' | 'Ļ' | 'Ľ' | 'Ŀ' | 'Ł' => "L".into(),
        'ĺ' | 'ļ' | 'ľ' | 'ŀ' | 'ł' => "l".into(),
        'Ñ' | 'Ń' | 'Ņ' | 'Ň' => "N".into(),
        'ñ' | 'ń' | 'ņ' | 'ň' => "n".into(),
        'Ò' | 'Ó' | 'Ô' | 'Õ' | 'Ö' | 'Ø' | 'Ō' | 'Ŏ' | 'Ő' | 'Ǒ' | 'Ȍ' | 'Ȏ' => {
            "O".into()
        }
        'ò' | 'ó' | 'ô' | 'õ' | 'ö' | 'ø' | 'ō' | 'ŏ' | 'ő' | 'ǒ' | 'ȍ' | 'ȏ' => {
            "o".into()
        }
        'Ŕ' | 'Ŗ' | 'Ř' => "R".into(),
        'ŕ' | 'ŗ' | 'ř' => "r".into(),
        'Ś' | 'Ŝ' | 'Ş' | 'Š' => "S".into(),
        'ś' | 'ŝ' | 'ş' | 'š' => "s".into(),
        'Ţ' | 'Ť' | 'Ŧ' => "T".into(),
        'ţ' | 'ť' | 'ŧ' => "t".into(),
        'Ù' | 'Ú' | 'Û' | 'Ü' | 'Ũ' | 'Ū' | 'Ŭ' | 'Ů' | 'Ű' | 'Ų' | 'Ǔ' | 'Ȕ' | 'Ȗ' => {
            "U".into()
        }
        'ù' | 'ú' | 'û' | 'ü' | 'ũ' | 'ū' | 'ŭ' | 'ů' | 'ű' | 'ų' | 'ǔ' | 'ȕ' | 'ȗ' => {
            "u".into()
        }
        'Ý' | 'Ÿ' | 'Ŷ' => "Y".into(),
        'ý' | 'ÿ' | 'ŷ' => "y".into(),
        'Ź' | 'Ż' | 'Ž' => "Z".into(),
        'ź' | 'ż' | 'ž' => "z".into(),
        'Æ' => "AE".into(),
        'æ' => "ae".into(),
        'Œ' => "OE".into(),
        'œ' => "oe".into(),
        _ => ch.to_string(),
    }
}
