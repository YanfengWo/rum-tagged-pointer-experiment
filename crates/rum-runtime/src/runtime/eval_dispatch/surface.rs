use super::*;

impl Session {
    pub(super) fn run_builtin_handler_surface(
        &mut self,
        handler: BuiltinHandler,
        head: &Expr,
        args: &[Expr],
    ) -> Result<Expr, EvalError> {
        match handler {
            BuiltinHandler::Identity => Ok(if args.len() == 1 {
                args[0].clone()
            } else {
                Expr::call(head.clone(), args.to_vec())
            }),
            BuiltinHandler::Plus => self.eval_plus(head, args),
            BuiltinHandler::Times => self.eval_times(head, args),
            BuiltinHandler::Power => self.eval_power(head, args),
            BuiltinHandler::Subtract => self.eval_subtract(head, args),
            BuiltinHandler::Divide => self.eval_divide(head, args),
            BuiltinHandler::Abs => self.eval_abs(head, args),
            BuiltinHandler::Factorial => self.eval_factorial(head, args),
            BuiltinHandler::Total => self.eval_total(head, args),
            BuiltinHandler::Denominator => self.eval_denominator(head, args),
            BuiltinHandler::Mod => self.eval_mod(head, args),
            BuiltinHandler::Quotient => self.eval_quotient(head, args),
            BuiltinHandler::PowerMod => self.eval_power_mod(head, args),
            BuiltinHandler::GCD => self.eval_gcd(head, args),
            BuiltinHandler::LCM => self.eval_lcm(head, args),
            BuiltinHandler::Expand => self.eval_expand(head, args),
            BuiltinHandler::Coefficient => self.eval_coefficient(head, args),
            BuiltinHandler::CoefficientList => self.eval_coefficient_list(head, args),
            BuiltinHandler::Together => self.eval_together(head, args),
            BuiltinHandler::Factor => self.eval_factor(head, args),
            BuiltinHandler::D => self.eval_d(head, args),
            BuiltinHandler::StringJoin => self.eval_string_join(head, args),
            BuiltinHandler::StringLength => self.eval_string_length(head, args),
            BuiltinHandler::ToUpperCase => self.eval_to_upper_case(head, args),
            BuiltinHandler::StringForm => self.eval_string_form(head, args),
            BuiltinHandler::StringRiffle => self.eval_string_riffle(head, args),
            BuiltinHandler::StringPadLeft => self.eval_string_pad_left(head, args),
            BuiltinHandler::StringTemplate => self.eval_string_template(head, args),
            BuiltinHandler::TemplateApply => self.eval_template_apply(head, args),
            BuiltinHandler::TextWords => self.eval_text_words(head, args),
            BuiltinHandler::ToCharacterCode => self.eval_to_character_code(head, args),
            BuiltinHandler::ToExpression => self.eval_to_expression(head, args),
            BuiltinHandler::StringToByteArray => self.eval_string_to_byte_array(head, args),
            BuiltinHandler::Hash => self.eval_hash(head, args),
            BuiltinHandler::Compress => self.eval_compress(head, args),
            BuiltinHandler::Uncompress => self.eval_uncompress(head, args),
            BuiltinHandler::Encrypt => self.eval_encrypt(head, args),
            BuiltinHandler::Decrypt => self.eval_decrypt(head, args),
            BuiltinHandler::Nearest => self.eval_nearest(head, args),
            BuiltinHandler::Pluralize => self.eval_pluralize(head, args),
            BuiltinHandler::SyntaxQ => self.eval_syntax_q(head, args),
            BuiltinHandler::TextString => self.eval_text_string(head, args),
            BuiltinHandler::FileTemplateApply => self.eval_file_template_apply(head, args),
            BuiltinHandler::CharacterCounts => self.eval_character_counts(head, args),
            BuiltinHandler::RemoveDiacritics => self.eval_remove_diacritics(head, args),
            BuiltinHandler::Alphabet => self.eval_alphabet(head, args),
            BuiltinHandler::AlphabeticSort => self.eval_alphabetic_sort(head, args),
            BuiltinHandler::EditDistance => self.eval_edit_distance(head, args),
            BuiltinHandler::HammingDistance => self.eval_hamming_distance(head, args),
            BuiltinHandler::LongestCommonSubsequence => {
                self.eval_longest_common_subsequence(head, args)
            }
            BuiltinHandler::SequenceAlignment => self.eval_sequence_alignment(head, args),
            BuiltinHandler::Diff => self.eval_diff(head, args),
            BuiltinHandler::Characters => self.eval_characters(head, args),
            BuiltinHandler::CharacterRange => self.eval_character_range(head, args),
            BuiltinHandler::ToString => self.eval_to_string(head, args),
            BuiltinHandler::StringRepeat => self.eval_string_repeat(head, args),
            BuiltinHandler::LetterQ => self.eval_letter_q(head, args),
            BuiltinHandler::DigitQ => self.eval_digit_q(head, args),
            BuiltinHandler::StringContainsQ => self.eval_string_contains_q(head, args),
            BuiltinHandler::StringStartsQ => self.eval_string_starts_q(head, args),
            BuiltinHandler::StringEndsQ => self.eval_string_ends_q(head, args),
            BuiltinHandler::StringPosition => self.eval_string_position(head, args),
            BuiltinHandler::StringSplit => self.eval_string_split(head, args),
            BuiltinHandler::StringTrim => self.eval_string_trim(head, args),
            BuiltinHandler::StringReplace => self.eval_string_replace(head, args),
            BuiltinHandler::StringCases => self.eval_string_cases(head, args),
            BuiltinHandler::StringApply => self.eval_string_apply(head, args),
            BuiltinHandler::StringDelete => self.eval_string_delete(head, args),
            BuiltinHandler::StringTake => self.eval_string_take(head, args),
            BuiltinHandler::StringDrop => self.eval_string_drop(head, args),
            BuiltinHandler::StringTakeDrop => self.eval_string_take_drop(head, args),
            BuiltinHandler::StringPart => self.eval_string_part(head, args),
            BuiltinHandler::StringCount => self.eval_string_count(head, args),
            BuiltinHandler::StringMatchQ => self.eval_string_match_q(head, args),
            BuiltinHandler::StringFreeQ => self.eval_string_free_q(head, args),
            BuiltinHandler::Trace => self.eval_trace(args),
            BuiltinHandler::TracePrint => self.eval_trace_print(args),
            BuiltinHandler::Timing => self.eval_timing(args),
            BuiltinHandler::AbsoluteTiming => self.eval_absolute_timing(args),
            BuiltinHandler::RepeatedTiming => self.eval_repeated_timing(args),
            BuiltinHandler::Short => self.eval_short(head, args),
            BuiltinHandler::Echo => self.eval_echo(head, args),
            BuiltinHandler::EchoFunction => self.eval_echo_function(head, args),
            BuiltinHandler::EchoLabel => self.eval_echo_label(head, args),
            BuiltinHandler::ByteCount => self.eval_byte_count(head, args),
            BuiltinHandler::On => self.eval_on(args),
            BuiltinHandler::Off => self.eval_off(args),
            BuiltinHandler::Sow => self.eval_sow(head, args),
            BuiltinHandler::Reap => self.eval_reap(args),
            BuiltinHandler::TimeConstrained => self.eval_time_constrained(args),
            BuiltinHandler::MemoryConstrained => self.eval_memory_constrained(args),
            BuiltinHandler::MemoryInUse => self.eval_memory_in_use(head, args),
            BuiltinHandler::Monitor => self.eval_monitor(args),
            BuiltinHandler::EvaluationData => self.eval_evaluation_data(args),
            BuiltinHandler::TestCreate => self.eval_test_create(head, args),
            BuiltinHandler::TestReport => self.eval_test_report(head, args),
            BuiltinHandler::Stack => self.eval_stack(args),
            BuiltinHandler::FullForm => self.eval_full_form(head, args),
            BuiltinHandler::Head => self.eval_head(head, args),
            BuiltinHandler::Length => self.eval_length(head, args),
            BuiltinHandler::Depth => self.eval_depth(head, args),
            BuiltinHandler::First => self.eval_first(head, args),
            BuiltinHandler::Last => self.eval_last(head, args),
            BuiltinHandler::Rest => self.eval_rest(head, args),
            BuiltinHandler::Most => self.eval_most(head, args),
            BuiltinHandler::Take => self.eval_take(head, args),
            BuiltinHandler::Drop => self.eval_drop(head, args),
            BuiltinHandler::TakeDrop => self.eval_take_drop(head, args),
            BuiltinHandler::Insert => self.eval_insert(head, args),
            BuiltinHandler::Delete => self.eval_delete(head, args),
            BuiltinHandler::TakeList => self.eval_take_list(head, args),
            BuiltinHandler::Range => self.eval_range(head, args),
            BuiltinHandler::Flatten => self.eval_flatten(head, args),
            BuiltinHandler::Join => self.eval_join(head, args),
            BuiltinHandler::Reverse => self.eval_reverse(head, args),
            BuiltinHandler::Transpose => self.eval_transpose(head, args),
            BuiltinHandler::DeleteDuplicates => self.eval_delete_duplicates(head, args),
            BuiltinHandler::DeleteDuplicatesBy => self.eval_delete_duplicates_by(head, args),
            BuiltinHandler::Sort => self.eval_sort(head, args),
            BuiltinHandler::SortBy => self.eval_sort_by(head, args),
            BuiltinHandler::Union => self.eval_union(head, args),
            BuiltinHandler::Complement => self.eval_complement(head, args),
            BuiltinHandler::Append => self.eval_append(head, args),
            BuiltinHandler::Prepend => self.eval_prepend(head, args),
            BuiltinHandler::Symbol => self.eval_symbol(head, args),
            BuiltinHandler::Construct => self.eval_construct(head, args),
            _ => self.run_builtin_handler_symbolic(handler, head, args),
        }
    }
}
